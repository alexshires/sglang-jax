def get_tuned_block_sizes(
    q_dtype,
    kv_dtype,
    actual_num_q_heads,
    actual_num_kv_heads,
    head_dim,
    page_size,
    max_num_tokens,
    pages_per_seq,
    causal=True,
) -> tuple[int, int]:
    if not causal:
        # FIXME(pc) hack this to avoid oom when precompile, currently, we still have no better choice for non-causal's mask
        # this should be optimied future
        return 4, 4
    """Look up for the best (num_kv_pages_per_blk, num_queries_per_blk) from auto-tuned table."""
    tpu_version = get_tpu_version()

    if tpu_version < 4:
        raise NotImplementedError("TPU version must be 4 or higher.")
    keys = get_simplified_key(
        page_size,
        q_dtype,
        kv_dtype,
        actual_num_q_heads,
        actual_num_kv_heads,
        head_dim,
        max_num_tokens,
    )

    device_name = keys[0]
    try:
        logical_device_count = get_logical_device_count()
        topology_name = get_device_name(num_devices=logical_device_count)
    except Exception:
        logger.debug("Failed to derive RPA topology name.", exc_info=True)
        topology_name = ""

    kernel_v11_enabled = os.getenv(_KERNEL_V11_ENV, "0") == "1"
    if (
        kernel_v11_enabled
        and device_name == "TPU v6e"
        and keys[1:7] == _KERNEL_V11_PAGE64_HOT_SHAPE
    ):

        def get_env_int(name: str, default: int) -> int:
            val = os.getenv(name)
            if val is None:
                return default
            try:
                return int(val)
            except ValueError:
                logger.warning(
                    "Invalid integer env for kernel-v11 override: %s=%r. Using default=%s.",
                    name,
                    val,
                    default,
                )
                return default

        decode_bkv = max(1, get_env_int(_KERNEL_V11_BKV_DECODE_ENV, 32))
        decode_bq = max(1, get_env_int(_KERNEL_V11_BQ_DECODE_ENV, 1))
        # 4096 is the largest short score-chunk bucket from the scorer sweep.
        # bq=40 won the small bucket despite not being a power-of-two tile.
        small_bkv = max(1, get_env_int(_KERNEL_V11_BKV_SMALL_ENV, 32))
        small_bq = max(1, get_env_int(_KERNEL_V11_BQ_SMALL_ENV, 40))
        large_bkv = max(1, get_env_int(_KERNEL_V11_BKV_LARGE_ENV, 32))
        large_bq = max(1, get_env_int(_KERNEL_V11_BQ_LARGE_ENV, 64))

        token_bucket = keys[7]
        if token_bucket <= 32:
            bkv_p, bq = (decode_bkv, decode_bq)
        elif token_bucket <= 4096:
            bkv_p, bq = (small_bkv, small_bq)
        else:
            bkv_p, bq = (large_bkv, large_bq)
        _log_rpa_policy_once(
            ("kernel-v11-hot-shape", device_name, page_size, token_bucket),
            logging.INFO,
            "Using kernel-v11 hot-shape override for %s: page_size=%s, max_num_tokens=%s, "
            "token_bucket=%s, decode=(%s,%s), small=(%s,%s), large=(%s,%s), selected=(%s,%s).",
            device_name,
            page_size,
            max_num_tokens,
            token_bucket,
            decode_bkv,
            decode_bq,
            small_bkv,
            small_bq,
            large_bkv,
            large_bq,
            bkv_p,
            bq,
        )
        return (min(pages_per_seq, bkv_p), min(max_num_tokens, bq))

    if (
        os.getenv(_V6E8_PAGE64_REPLICA_ENV, "0") == "1"
        and topology_name == "TPU v6e-8"
        and device_name == "TPU v6e"
        and page_size == 64
        and head_dim == 128
    ):
        # Opt-in because this branch affects every matching RPA caller on v6e-8,
        # not only score-from-cache requests.
        token_bucket = next_power_of_2(max_num_tokens)
        if token_bucket <= 32:
            bkv_p, bq = (32, 1)
        elif token_bucket <= 4096:
            bkv_p, bq = (32, 96)
        else:
            bkv_p, bq = (32, 128)
        _log_rpa_policy_once(
            ("v6e8-page64-replica", device_name, token_bucket),
            logging.INFO,
            "Using TPU v6e-8 replica-lane page64 override: token_bucket=%s, selected=(%s,%s).",
            token_bucket,
            bkv_p,
            bq,
        )
        return (min(pages_per_seq, bkv_p), min(max_num_tokens, bq))

    # Default block sizes.
    bkv_p, bq = (1024 // page_size, 32)
    if tpu_version == 4:
        # TPUv4 has much smaller VMEM size so we pick fixed block sizes.
        bkv_p, bq = (512 // page_size, 32)
    else:
        if device_name in TUNED_BLOCK_SIZES and keys[1:] in TUNED_BLOCK_SIZES[device_name]:
            bkv_p, bq = TUNED_BLOCK_SIZES[device_name][keys[1:]]
        else:
            tuned_table = TUNED_BLOCK_SIZES.get(device_name, {})
            fallback = _get_page_size_fallback_tuned_block_size(
                tuned_table=tuned_table,
                keys_without_device=keys[1:],
                page_size=page_size,
                max_num_tokens=max_num_tokens,
            )
            if fallback is not None:
                bkv_p, bq, fb_page_size, fb_tokens = fallback
                _log_rpa_policy_once(
                    ("page-size-fallback", device_name, page_size, max_num_tokens),
                    logging.WARNING,
                    "Using fallback tuned block size for %s: requested(page_size=%s, max_num_tokens=%s) "
                    "-> tuned(page_size=%s, max_num_tokens=%s), bkv_p=%s, bq=%s.",
                    device_name,
                    page_size,
                    max_num_tokens,
                    fb_page_size,
                    fb_tokens,
                    bkv_p,
                    bq,
                )
            else:
                logger.info(
                    "Tuned RPA block sizes not found for %s: page_size=%s, actual_num_q_heads=%s, "
                    "actual_num_kv_heads=%s, head_dim=%s, max_num_tokens=%s, pages_per_seq=%s.",
                    device_name,
                    page_size,
                    actual_num_q_heads,
                    actual_num_kv_heads,
                    head_dim,
                    max_num_tokens,
                    pages_per_seq,
                )
                logger.info("Using default block size: bkv_p=%s, bq=%s.", bkv_p, bq)

    # if bkv_p != 16 or bq != 16:
    #     raise ValueError(
    #         f"Invalid block sizes: {keys=}, {bkv_p=}, {bq=}. Please check {page_size=}, {actual_num_q_heads=}, {actual_num_kv_heads=}, {head_dim=}, {max_num_tokens=}, {pages_per_seq=}"
    #     )

    return (min(pages_per_seq, bkv_p), min(max_num_tokens, bq))


def get_simplified_key(
    page_size,
    q_dtype,
    kv_dtype,
    num_q_heads,
    num_kv_heads,
    head_dim,
    max_num_tokens,
):
    """Get the simplified key to reduce the number of combinations."""
    assert num_q_heads % num_kv_heads == 0
    device = get_device_name()
    q_dtype_name = jnp.dtype(q_dtype).name
    kv_dtype_name = jnp.dtype(kv_dtype).name
    num_q_heads = next_power_of_2(num_q_heads)
    num_kv_heads = next_power_of_2(num_kv_heads)

    return (
        device,
        q_dtype_name,
        kv_dtype_name,
        num_q_heads,
        num_kv_heads,
        (head_dim + 127) // 128 * 128,
        next_power_of_2(page_size),
        next_power_of_2(max_num_tokens),
    )
